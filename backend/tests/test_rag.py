def test_chunking_service_boundaries():
    """Verify chunking preserves sentence boundaries and respects max length."""
    text = (
        "Small Language Models operate locally. "
        "They deliver low latency and private data execution. "
        "ChromaDB stores dense vector representations. "
        "Sentence transformers map queries to 384-dimensional vectors."
    )
    chunks = chunking_service.split_text(text, chunk_size=80, chunk_overlap=15)
    assert len(chunks) >= 2
    for c in chunks:
        assert len(c["content"]) <= 120
        assert "char_length" in c


def test_rag_document_upload_and_search(client: TestClient):
    """Test full document upload, ChromaDB indexing, and similarity search."""
    sample_content = (
        "Local SLM Laboratory Technical Specification.\n\n"
        "Qwen 2.5 3B has approximately 3.09 billion actual parameters.\n\n"
        "The model uses 384-dimensional embeddings generated by all-MiniLM-L6-v2."
    )
    file_bytes = io.BytesIO(sample_content.encode("utf-8"))

    # 1. Upload Document
    upload_res = client.post(
        "/api/rag/documents",
        files={"file": ("tech_specs.txt", file_bytes, "text/plain")},
        data={"chunk_size": 200, "chunk_overlap": 20},
    )
    assert upload_res.status_code == 201
    doc_data = upload_res.json()
    doc_id = doc_data["id"]
    assert doc_data["filename"] == "tech_specs.txt"
    assert doc_data["chunk_count"] > 0

    # 2. List Documents
    list_res = client.get("/api/rag/documents")
    assert list_res.status_code == 200
    docs = list_res.json()
    assert any(d["id"] == doc_id for d in docs)

    # 3. Vector Similarity Search
    search_res = client.post(
        "/api/rag/search",
        json={"query": "How many parameters does Qwen 2.5 3B have?", "top_k": 2},
    )
    assert search_res.status_code == 200
    results = search_res.json()
    assert len(results) > 0
    assert "3.09 billion" in results[0]["content"]
    assert results[0]["relevance_score"] > 0.0

    # 4. Delete Document & Verify Chroma Vectors are purged
    del_res = client.delete(f"/api/rag/documents/{doc_id}")
    assert del_res.status_code == 204

    # Verify document no longer in list
    list_after = client.get("/api/rag/documents").json()
    assert not any(d["id"] == doc_id for d in list_after)


def test_rag_query_with_mocked_model(client: TestClient):
    """Test grounded Q&A answering pipeline with simulated inference."""
    # Upload sample knowledge
    sample_content = "All-MiniLM-L6-v2 maps text passages into 384-dimensional dense vectors."
    file_bytes = io.BytesIO(sample_content.encode("utf-8"))
    upload_res = client.post(
        "/api/rag/documents",
        files={"file": ("embeddings_guide.txt", file_bytes, "text/plain")},
    )
    doc_id = upload_res.json()["id"]

    mock_reply = {
        "model": "qwen2.5:3b",
        "content": "According to the guide, all-MiniLM-L6-v2 generates 384-dimensional dense vectors [Document: embeddings_guide.txt].",
        "latency_ms": 320.0,
        "ttft_ms": 40.0,
        "tokens_per_second": 35.0,
        "input_tokens": 55,
        "output_tokens": 20,
    }

    with patch("app.services.rag_service.ollama_service.chat_completion", new_callable=AsyncMock) as mock_chat:
        mock_chat.return_value = mock_reply

        query_res = client.post(
            "/api/rag/query",
            json={"query": "What vector dimension is produced?", "model_tag": "qwen2.5:3b", "top_k": 2},
        )
        assert query_res.status_code == 200
        data = query_res.json()
        assert "384-dimensional" in data["answer"]
        assert len(data["retrieved_passages"]) > 0
        assert data["is_grounded"] is True
        assert data["insufficient_evidence"] is False

    # Cleanup
    client.delete(f"/api/rag/documents/{doc_id}")


def test_rag_evaluator_metrics():
    """Verify RAGEvaluator metrics for grounded answers, citations, and abstention."""
    task = {
        "question": "What is the parameter size of Qwen 2.5 3B?",
        "expected_source": "whitepaper.pdf",
        "required_keywords": ["3.09", "billion"],
        "requires_abstention": False,
    }
    retrieved = [
        {"filename": "whitepaper.pdf", "page_number": 1, "content": "Qwen 2.5 3B has 3.09 billion parameters."}
    ]
    good_answer = "Qwen 2.5 3B has 3.09 billion parameters [Document: whitepaper.pdf, Page: 1]."
    result = RAGEvaluator.evaluate(task, good_answer, retrieved)
    assert result["is_success"] is True
    assert result["score"] >= 0.8
    assert result["metrics"]["recall_at_k"] == 1.0
    assert result["metrics"]["citation_count"] == 1

    # Abstention test
    abstain_task = {
        "question": "What is the speed of light on Neptune?",
        "requires_abstention": True,
    }
    abstain_answer = "Insufficient evidence in the provided documents to answer this question."
    abstain_result = RAGEvaluator.evaluate(abstain_task, abstain_answer, [])
    assert abstain_result["is_success"] is True
    assert abstain_result["score"] == 1.0

    # Answer with correct facts and citation plus a cautious hedging note
    hedged_answer = (
        "The model parameter count is approximately 3.09 billion [Document: whitepaper.pdf, Page: 1]. "
        "Insufficient evidence in the provided documents to answer whether this is exact."
    )
    hedged_result = RAGEvaluator.evaluate(task, hedged_answer, retrieved)
    assert hedged_result["is_success"] is True
    assert hedged_result["score"] >= 0.70
